/* =========================================================================
   文字くらべ
   ひらがな/カタカナ、全角/半角、長音、記号、空白のちがいを無視して
   同じ言葉かどうかを見る。漢字とかなのちがいまでは吸収できないので、
   出題者が手で正解にできるボタンを各ゲームに用意してある。
   ========================================================================= */
function norm(s) {
  let t = String(s == null ? '' : s).normalize('NFKC').toLowerCase();
  t = t.replace(/[\s　]/g, '');
  t = t.replace(/[ー－―‐\-~〜、。,.!?！？「」『』()（）・:：;；"'`]/g, '');
  /* ひらがな → カタカナ */
  t = t.replace(/[ぁ-ゖ]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60));
  /* 小さいカナ → 大きいカナ、濁点をはずす */
  const small = 'ァィゥェォッャュョヮヵヶ';
  const large = 'アイウエオツヤユヨワカケ';
  t = t.replace(/[ァィゥェォッャュョヮヵヶ]/g, (c) => large[small.indexOf(c)]);
  t = t.normalize('NFD').replace(/[゙゚]/g, '').normalize('NFC');
  return t;
}

function sameWord(a, b) {
  const x = norm(a);
  return x.length > 0 && x === norm(b);
}

/* 配列からランダムに1つ。直前と同じものは避ける。 */
function pickWord(list, avoid) {
  for (let i = 0; i < 20; i++) {
    const w = list[Math.floor(Math.random() * list.length)];
    if (w !== avoid) return w;
  }
  return list[0];
}

function shuffled(list) {
  const a = list.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const t = a[i]; a[i] = a[j]; a[j] = t;
  }
  return a;
}
